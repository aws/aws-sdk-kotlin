package aws.sdk.kotlin.benchmarks.serde

import kotlinx.coroutines.runBlocking
import aws.sdk.kotlin.benchmarks.serde.awsjsonrpc10.registerBenchmarks as registerAwsJsonRpc10
import aws.sdk.kotlin.benchmarks.serde.awsquery.registerBenchmarks as registerAwsQuery
import aws.sdk.kotlin.benchmarks.serde.awsrestjson.registerBenchmarks as registerAwsRestJson
import aws.sdk.kotlin.benchmarks.serde.awsrestxml.registerBenchmarks as registerAwsRestXml
import aws.sdk.kotlin.benchmarks.serde.smithyrpcv2cbor.registerBenchmarks as registerSmithyRpcV2Cbor

/**
 * Runs all registered serde benchmarks.
 *
 * Each projection's [registerBenchmarks] function is generated by codegen and
 * provides direct references to benchmark classes — no runtime reflection needed.
 */

private fun registerAllProtocols() {
    registerAwsRestJson()
    registerAwsJsonRpc10()
    registerSmithyRpcV2Cbor()
    registerAwsRestXml()
    registerAwsQuery()
}

fun main() = runBlocking {
    registerAllProtocols()

    val allResults = mutableListOf<BenchmarkResult>()

    for (entry in BenchmarkRegistry.entries) {
        println("Running: ${entry.name}")
        val benchmark = entry.create()
        val results = benchmark.benchmarks()
        allResults.addAll(results)
        println("  Completed ${results.size} test cases")
    }

    val metadata = KotlinBenchmarkMetadata(
        smithyKotlinVersion = System.getProperty("smithy.kotlin.version", "SNAPSHOT"),
        sdkVersion = System.getProperty("aws.sdk.kotlin.version", "SNAPSHOT"),
    )
    println()
    println(BenchmarkHarness.toJson(metadata, allResults))
}
